// [Claude 2026-10-20] bake real dice throws for the clubhouse dice table -> src/dicethrows.js (module 'dicethrows').
// The 2026-10-18 simulation threw the dice with cannon-es physics; the game has no physics engine, so a few good throws are
// recorded here once (both dice hit the far wall and lie flat on the felt) and the table plays one back, each die turned so the
// face the Bank decided lands up (dicetable.js, as the simulation's turnFor). Run with cannon-es + three installed:
//   cp tools/tables/bake_throws.mjs <dir with node_modules>/ && OUT=$PWD/src/dicethrows.js node <dir>/bake_throws.mjs
import * as CANNON from 'cannon-es';
import * as THREE from 'three';
import fs from 'fs';
const S = 0.8, BED_L = 3.2, BED_W = 1.14, BED_Y = 0.78 * S, HL = BED_L / 2, HW = BED_W / 2, DIE = 0.022;   // = src/dicetable.js (2026-10-21: a 12-foot table in true metres, 22 mm dice)
const FACE_AXIS = { 1: [0, 1, 0], 2: [1, 0, 0], 3: [0, 0, 1], 4: [0, 0, -1], 5: [-1, 0, 0], 6: [0, -1, 0] };
function simulate(seed) {
  let s = seed >>> 0; const rnd = () => { s = (s * 1664525 + 1013904223) >>> 0; return s / 4294967296; };
  const w = new CANNON.World({ gravity: new CANNON.Vec3(0, -9.82, 0), allowSleep: true });
  const mat = new CANNON.Material(); w.addContactMaterial(new CANNON.ContactMaterial(mat, mat, { friction: 0.25, restitution: 0.42 }));
  const floor = new CANNON.Body({ type: CANNON.Body.STATIC, shape: new CANNON.Plane(), material: mat }); floor.quaternion.setFromEuler(-Math.PI / 2, 0, 0); floor.position.y = BED_Y; w.addBody(floor);
  const wall = (hx, hz, x, z) => { const b = new CANNON.Body({ type: CANNON.Body.STATIC, shape: new CANNON.Box(new CANNON.Vec3(hx, 0.4, hz)), material: mat }); b.position.set(x, BED_Y + 0.4, z); w.addBody(b); return b; };
  const far = wall(0.05, HW, -HL - 0.05, 0); wall(0.05, HW, HL + 0.05, 0); wall(HL, 0.05, 0, -HW - 0.05); wall(HL, 0.05, 0, HW + 0.05);
  const bodies = [0, 1].map(i => { const b = new CANNON.Body({ mass: 0.012, shape: new CANNON.Box(new CANNON.Vec3(DIE / 2, DIE / 2, DIE / 2)), material: mat, sleepTimeLimit: 0.25, sleepSpeedLimit: 0.05, linearDamping: 0.08, angularDamping: 0.08 });
    b.position.set(HL - 0.12, BED_Y + 0.22 + i * 0.04, HW * 0.55 + (i - 0.5) * 0.05); b.quaternion.setFromEuler(rnd() * 6.28, rnd() * 6.28, rnd() * 6.28);
    b.velocity.set(-(3.9 + rnd() * 1.0), 0.9 + rnd() * 0.6, -(0.25 + rnd() * 0.35)); b.angularVelocity.set((rnd() - 0.5) * 40, (rnd() - 0.5) * 40, (rnd() - 0.5) * 40); w.addBody(b); return b; });
  const hit = [false, false]; bodies.forEach((b, i) => b.addEventListener('collide', e => { if (e.body === far) hit[i] = true; }));
  const frames = [];
  for (let k = 0; k < 120 * 6; k++) { w.step(1 / 120); if (k % 4 === 0) frames.push(bodies.map(b => [b.position.x, b.position.y, b.position.z, b.quaternion.x, b.quaternion.y, b.quaternion.z, b.quaternion.w]));
    if (k > 60 && bodies.every(b => b.sleepState === CANNON.Body.SLEEPING)) break; }
  const up = [], flat = [];
  for (const b of bodies) { const q = new THREE.Quaternion(b.quaternion.x, b.quaternion.y, b.quaternion.z, b.quaternion.w); let best = 0, bv = -2;
    for (const f of [1, 2, 3, 4, 5, 6]) { const v = new THREE.Vector3(...FACE_AXIS[f]).applyQuaternion(q).y; if (v > bv) { bv = v; best = f; } } up.push(best); flat.push(bv > 0.985); }
  const onBed = bodies.every(b => b.position.y < BED_Y + DIE * 0.7 && Math.abs(b.position.x) < HL && Math.abs(b.position.z) < HW);
  const apart = Math.hypot(bodies[0].position.x - bodies[1].position.x, bodies[0].position.z - bodies[1].position.z) > DIE * 1.6;
  return { frames, up, ok: hit[0] && hit[1] && flat[0] && flat[1] && onBed && apart };
}
const throws = [];
for (let seed = 1; throws.length < 6 && seed < 5000; seed++) {
  const t = simulate(seed * 7919); if (!t.ok) continue;
  // quantize: positions in millimetres, quaternions in 1/1000
  const f = []; for (const fr of t.frames) for (const d of fr) f.push(...d.map(v => Math.round(v * 1e3)));
  throws.push({ up: t.up, n: t.frames.length, f });
}
const js = `/* ASHVALE: the dice table's recorded throws (generated by tools/tables/bake_throws.mjs from cannon-es physics, ${new Date().toISOString().slice(0, 10)}; do not edit).
   Each throw: up (the faces the physics left up), n frames at 30 a second, f = n x 2 dice x [x, y, z, qx, qy, qz, qw] (x1000) in the
   table's own frame (src/dicetable.js: the shooter's end +x, the far wall -x). */
(function (G) {
  'use strict';
  const API = { FPS: 30, DIE: ${DIE}, THROWS: ${JSON.stringify(throws)} };
  if (G.ASH3D && G.ASH3D.define) G.ASH3D.define('dicethrows', { api: 1, v: 1, needs: {} }, () => API);
  if (typeof module !== 'undefined' && module.exports) module.exports = API;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
fs.writeFileSync(process.env.OUT || 'src/dicethrows.js', js);
console.log('throws', throws.length, 'frames', throws.map(t => t.n).join(','), 'bytes', js.length);
